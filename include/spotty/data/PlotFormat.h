/**
 * \file PlotFormat.h
 * \brief Короткие подписи плоттера: имена рядов по умолчанию и числа под заданную ширину.
 */
#pragma once

#include <spotty/api/SpottyApiExport.h>

#include <QString>

namespace spotty {

/**
 * \class PlotFormat
 * \brief Превращение данных плоттера в короткие строки для показа.
 *
 * Все методы статические; класс существует как пространство имён — так же, как
 * spotty::Formatting и spotty::FileUtils.
 *
 * Здесь нет ни одного виджета намеренно: подбор числа знаков зависит от ширины поля в
 * знакоместах, а не в пикселях, поэтому перевод пикселей в знакоместа (единственное, что
 * требует QFontMetrics, а значит QtGui) остаётся за слоем интерфейса, а само правило
 * проверяется тестами без QApplication.
 */
class SPOTTY_API_EXPORT PlotFormat
{
public:
    /// \brief Сколько имён даёт алфавит ИКАО, прежде чем начнутся номера.
    static constexpr int kNamedSeriesCount = 26;

    /**
     * \brief Имя ряда по умолчанию: `alpha`, `bravo`, `charlie`, …
     * \param index Номер колонки, считая с нуля.
     * \return Имя из алфавита ИКАО; начиная с 27-й колонки — её номер строкой.
     *
     * Алфавит вместо прежнего «Column N», потому что имя ряда попадает в подпись курсора,
     * в узкую колонку таблицы и в заголовок экспорта — всюду, где ширина на счету. К тому
     * же «Column 11» и «Column 12» различаются одним знаком в конце и путаются взглядом,
     * а `kilo` и `lima` не путаются ничем.
     *
     * \note Без `tr()`: это собственные имена, одинаковые во всех языках. Перевод сломал бы
     *       ровно то, ради чего алфавит и заведён, — различимость имён между собой.
     */
    static QString defaultSeriesName(int index);

    /**
     * \brief Сколько значащих цифр показывать в поле шириной \p characters знакомест.
     * \param characters Ширина поля в знакоместах моноширинного шрифта.
     * \return От 3 до 9 значащих цифр.
     *
     * Три знакоместа уходят на минус, десятичную точку и запас на округление. Запись `'g'`
     * при этом умеет выйти за бюджет — `-1.2346e-05` длиннее любой оценки, — но перекрытие
     * снимается многоточием в таблице, а не сужением числа: иначе одно выпавшее значение
     * меняло бы точность всей колонки.
     *
     * \note Число знаков **не зависит от значения** — только от ширины. Это и есть требование
     *       владельца: цифры не должны прыгать, пока меняются данные. Ширина же меняется
     *       лишь тогда, когда пользователь сам тянет край панели.
     */
    static int digitsForCharacters(int characters);

    /**
     * \brief Число значащими цифрами; нечисло даёт тире.
     * \param value Значение; NaN и бесконечности дают `"—"`.
     * \param digits Число значащих цифр, обычно из digitsForCharacters().
     *
     * Тире, а не `"nan"` и не пустая ячейка: пустая читается как «ещё не посчитано», а
     * `nan` — как неисправность, тогда как отсутствующий отсчёт в потоке телеметрии дело
     * обычное. Тире прямо говорит «значения тут нет».
     */
    static QString number(double value, int digits);

    /**
     * \brief Число под ширину поля; не поместившееся заменяется многоточием.
     * \param value Значение.
     * \param characters Ширина поля в знакоместах.
     *
     * Число знаков берётся из digitsForCharacters() и **не подгоняется под значение**:
     * ужимать точность ради того, чтобы влезло, значило бы показывать соседние строки с
     * разной точностью, а одну и ту же строку — с разной в разные секунды. Ровно от этого
     * владелец и просил избавиться.
     *
     * Поэтому не влезшее показывается многоточием, а не обрезком. Обрезанное число — это
     * **другое** число: «1234…» от 1234567 отличается на три порядка, и прочитавший его
     * сделает неверный вывод, ничего не заподозрив. Многоточие же прямо говорит «расширь
     * колонку».
     */
    static QString fitted(double value, int characters);

    /**
     * \brief Среднее под ширину поля, с ограниченной дробной частью.
     * \param value Значение.
     * \param characters Ширина поля в знакоместах.
     * \param maximumDecimals Сколько знаков после запятой оставить.
     *
     * Среднее — единственное вычисленное из трёх чисел, и оно почти никогда не бывает
     * круглым: среднее целых 1, 2 и 2 равно 1.6666667, и шесть знаков после запятой тут не
     * точность, а шум — исходные данные её не несли. Минимум и максимум, наоборот,
     * настоящие отсчёты, и округлять их значило бы показывать значение, которого прибор не
     * выдавал.
     *
     * Ограничение действует только для значений не меньше единицы: у 0.000123 обрезание
     * дробной части не оставило бы ничего, и там по-прежнему работают значащие цифры.
     */
    static QString fittedMean(double value, int characters, int maximumDecimals = 3);
};

} // namespace spotty
