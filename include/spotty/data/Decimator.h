/**
 * \file Decimator.h
 * \brief Сведение ряда отсчётов к разрешению поля графика.
 */
#pragma once

#include <spotty/api/SpottyApiExport.h>
#include <spotty/data/PlotTransform.h>
#include <spotty/data/SampleBuffer.h>

#include <QList>

#include <optional>

namespace spotty {

/**
 * \class Decimator
 * \brief Пара точек на пиксельную колонку: наибольшее и наименьшее из попавших в неё.
 *
 * \par Почему в единицах данных, а не сразу в пикселях
 *
 * Видимые пределы ряда выпадают из того же прохода, который и так уже идёт, поэтому
 * автомасштаб по ряду достаётся бесплатно: отдельного прохода нет, и шкала не отстаёт на
 * кадр. Перевод в пиксели остаётся за виджетом, где известна геометрия поля — и это же
 * позволяет проверять всё здешнее без QApplication.
 *
 * \par Почему корзины по координате, а не по номеру отсчёта
 *
 * Раньше ряд растягивался на всю ширину по числу своих точек. Пачка данных, пришедшая за
 * миллисекунду, занимала столько же места, сколько минута тишины, а два ряда разной длины
 * ложились в разных масштабах друг поверх друга. Корзина здесь — отрезок горизонтальной
 * координаты (времени приёма или счётчика устройства), поэтому пачка занимает свою долю
 * ширины, а ряды заведомо совпадают по горизонтали.
 */
class SPOTTY_API_EXPORT Decimator
{
public:
    /**
     * \brief Масштаб фиксированной точки для дробной координаты устройства.
     *
     * Состояние горизонтального окна исторически хранится в qint64. Шесть знаков после
     * запятой покрывают типичные счётчики (секунды, шаги, обороты), при этом диапазон
     * остаётся около девяти триллионов целых единиц и не переполняется на длинном сеансе.
     */
    static constexpr qint64 kCounterCoordinateScale = 1'000'000LL;

    /// \brief Что накапливать по ходу прохода.
    enum class Accumulator {
        None,       ///< Значения как есть.
        RunningSum, ///< Бегущая сумма от начала буфера — режим накопления.
    };

    /**
     * \struct Column
     * \brief Пиксельная колонка: её номер и пределы попавших в неё значений.
     */
    struct Column
    {
        int x = 0;
        double minimum = 0.0;
        double maximum = 0.0;
    };

    /**
     * \struct Result
     * \brief Свёрнутый ряд вместе с его видимыми пределами.
     */
    struct Result
    {
        QList<Column> columns;

        /**
         * \brief Индексы в #columns, с которых начинается новый отрезок кривой.
         *
         * Пропуск (NaN) рвёт кривую: соединив соседей прямой, мы показали бы данные,
         * которых устройство не присылало. Первый отрезок начинается с нуля, поэтому список
         * непуст всегда, когда есть хоть одна колонка.
         */
        QList<int> runStarts;

        PlotScales::Range visible;
    };

    /**
     * \brief Свести колонку буфера к \p pixelColumns колонкам.
     * \param buffer Источник отсчётов.
     * \param column Номер колонки в буфере.
     * \param transform Окно горизонтальной координаты; поля left и width не используются.
     * \param pixelColumns Сколько колонок в поле графика; не больше — разрешения нет.
     * \param accumulator Что накапливать по ходу.
     * \param maximumConnectedGap Самая длинная пауза без разрыва; ноль — вычислить.
     * \param coordinateColumn Колонка монотонного счётчика для X; -1 — метка получения.
     *
     * В результат попадают также по одному отсчёту непосредственно до и после окна — в
     * колонках `-1` и `pixelColumns`. Виджет обрежет их границей поля, зато кривая не
     * оборвётся у края при сильном увеличении. Эти отсчёты не входят в `visible` и потому
     * не меняют автоматическую вертикальную шкалу.
     */
    static Result reduce(const SampleBuffer &buffer, int column, const XTransform &transform,
                         int pixelColumns, Accumulator accumulator = Accumulator::None,
                         qint64 maximumConnectedGap = 0, int coordinateColumn = -1);

    /**
     * \brief Наибольший разрыв горизонтальной координаты, который ещё соединяется линией.
     *
     * Типичный интервал берётся медианой по буферу: единичная задержка не превращает
     * нормальный ритм в «медленный». Три таких интервала отделяют реальную паузу, а
     * минимум в три пикселя не рвёт линию из-за координатного зазора, которого глаз всё
     * равно не видит.
     *
     * \return Порог в единицах выбранной координаты; всегда положителен при ненулевом окне.
     */
    static qint64 maximumConnectedGap(const SampleBuffer &buffer, const XTransform &transform,
                                      int pixelColumns, int coordinateColumn = -1);

    /**
     * \brief Номер первой строки с координатой не меньше \p coordinate.
     *
     * Двоичный поиск по неубывающим меткам: именно он делает масштабирование по
     * пятидесяти тысячам отсчётов дешёвым — окно находится за логарифм, а не за проход.
     */
    static int lowerBound(const SampleBuffer &buffer, qint64 coordinate,
                          int coordinateColumn = -1);

    /**
     * \brief Координата строки по времени получения либо дробному счётчику.
     *
     * Счётчик кодируется фиксированной точкой с #kCounterCoordinateScale делений на
     * единицу. Нечисленная, выходящая за безопасный диапазон qint64 или отсутствующая
     * координата возвращает пустое значение: подменять её временем означало бы незаметно
     * склеить разные оси.
     */
    static std::optional<qint64> coordinateAt(const SampleBuffer &buffer, int row,
                                               int coordinateColumn = -1);
};

} // namespace spotty
