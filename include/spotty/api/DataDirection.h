/**
 * \file DataDirection.h
 * \brief Происхождение порции данных.
 */
#pragma once

#include <QtGlobal>

namespace spotty {

/**
 * \enum DataDirection
 * \brief Откуда взялись данные строки.
 *
 * Живёт в SDK, а не рядом с буфером терминала, потому что им размечены сразу три
 * контракта: сигнал spotty::Session::dataLogged, запись журнала и звенья цепочки
 * преобразования потока. Плагину, который смотрит на поток, тип нужен, а буфер терминала
 * ему недоступен.
 *
 * \note Значения дописываются только в конец: перечисление пересекает границу модуля и
 *       попадает в уже собранные плагины.
 */
enum class DataDirection : quint8 {
    Rx,     ///< Принято от устройства.
    Tx,     ///< Отправлено нами и отражено в терминал.
    System, ///< Сообщение самой программы: открытие порта, ошибка, разрыв связи.
};

} // namespace spotty
