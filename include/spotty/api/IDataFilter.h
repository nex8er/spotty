/**
 * \file IDataFilter.h
 * \brief Звено цепочки преобразования потока данных.
 */
#pragma once

#include <QByteArray>

namespace spotty {

/**
 * \class IDataFilter
 * \brief Звено цепочки преобразования потока между проводом и терминалом.
 *
 * \par Зачем
 *
 * Наблюдать за потоком можно и сигналом. Фильтр нужен там, где данные требуется
 * **изменить** до того, как их увидит терминал: распаковать кадр протокола, склеить
 * разорванную посылку, вырезать служебные байты, подменить содержимое.
 *
 * \par Где живёт контракт
 *
 * В основном SDK, а не в панельном, хотя пользуются им плагины панелей. Цепочку применяет
 * spotty::Session, а он в `spotty-core`, которому Qt6::Widgets запрещён. Поместить
 * интерфейс в панельный SDK значило бы затащить Widgets в ядро.
 *
 * \par Порядок
 *
 * Звенья выстроены по числу, объявленному плагином. Приёмная цепочка идёт по возрастанию,
 * передающая — **в обратную сторону**, как в стеке протоколов: что приёмное звено
 * развернуло последним, передающее сворачивает первым.
 *
 * \warning Оба метода вызываются в потоке пользовательского интерфейса, на каждой порции
 *          данных. На 3 Мбод это сотни вызовов в секунду, и медленное звено съедает поток
 *          целиком — окно перестаёт отвечать. Требование той же силы, что к
 *          spotty::IInterfacePlugin::enumerate().
 */
class IDataFilter
{
public:
    virtual ~IDataFilter() = default;

    /**
     * \brief Преобразовать принятые байты.
     * \param data Выход предыдущего звена; для первого — то, что пришло от канала.
     * \param monotonicNs Отметка чтения, поставленная каналом.
     * \return Байты для следующего звена. Пустой массив проглатывает порцию целиком:
     *         ни дальше по цепочке, ни в терминал не уйдёт ничего.
     *
     * \note Отметку времени звено не задаёт и вернуть не может. Байты, придержанные от
     *       прошлой порции и выпущенные сейчас, получают время текущей — то есть время
     *       последнего байта кадра. Это не уступка удобству: именно последний байт нужен и
     *       относительным меткам в терминале («сколько устройство думало» — до конца
     *       ответа), и разбиению потока по межбайтовой паузе.
     */
    virtual QByteArray filterIncoming(const QByteArray &data, qint64 monotonicNs) = 0;

    /**
     * \brief Преобразовать отправляемые байты.
     * \return Байты для следующего звена. Пустой массив отменяет отправку — это законное
     *         решение звена, а не сбой, и об ошибке никто не сообщает.
     *
     * По умолчанию поток не трогается: большинству звеньев нужно только приёмное
     * направление.
     */
    virtual QByteArray filterOutgoing(const QByteArray &data) { return data; }
};

} // namespace spotty
