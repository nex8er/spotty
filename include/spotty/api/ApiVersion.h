/**
 * \def SPOTTY_API_VERSION
 * \brief Версия двоичного интерфейса плагинов.
 *
 * Увеличивается при любом изменении, ломающем уже собранные плагины: смена сигнатуры
 * виртуального метода, удаление метода, изменение порядка виртуальных функций, изменение
 * раскладки структур, передаваемых через API.
 *
 * spotty::PluginManager отказывается загружать плагин, у которого
 * spotty::IInterfacePlugin::apiVersion() не совпадает с этим значением, и показывает
 * причину пользователю. Это лучше, чем падение при первом же вызове по несуществующему
 * адресу в таблице виртуальных функций.
 *
 * \note Добавление нового виртуального метода **в конец** класса с реализацией по
 *       умолчанию тоже ломает ABI для уже собранных плагинов, потому что смещения в
 *       vtable сдвигаются. Версию нужно увеличивать и в этом случае.
 *
 * \par История
 *
 * - **5** — устройства, которые заводит сам пользователь: spotty::IInterfacePlugin::supportsUserDevices()
 *   и spotty::IInterfacePlugin::describeUserDevice() (подключение по сети, у которого нет
 *   ни порта в системе, ни серийного номера, чтобы его перечислить), spotty::IInterfacePlugin::setDataDirectory()
 *   (собственный каталог плагина, например для отпечатков известных ssh-хостов) и тип поля
 *   spotty::SettingsField::Password — значение живёт только в памяти, — а также spotty::IInterfacePlugin::promptSchema()
 *   (окно вопроса перед действием: имя и пароль ssh, которые не должны попадать в настройки) и
 *   поля spotty::SettingsField::advanced, spotty::SettingsField::compact и
 *   spotty::SettingsField::primary, а также spotty::NoteSeverity — как плагин подаёт строку
 *   сведений (успех, предупреждение, сбой). Четыре виртуальных метода дописаны в конец, но, как
 *   сказано выше, это тоже сдвигает vtable; три поля дописаны в конец spotty::SettingsField, и
 *   раскладка структуры изменилась.
 * - **4** — типы полей spotty::SettingsField::Note и spotty::SettingsField::Action и метод
 *   spotty::IInterfacePlugin::triggerAction(): строка состояния и кнопка в диалоге
 *   настроек (наличие драйвера com0com у перехватчика порта на Windows). Новый
 *   виртуальный метод сдвигает vtable; раскладка самой структуры поля не менялась.
 * - **3** — сигнал spotty::IInterfaceChannel::dataTransmitted(): перехватчик порта видит и
 *   то, что чужая программа посылает устройству. Старые плагины сигналом не затронуты —
 *   он дописан в конец, — но новый плагин на прежнем ядре испустил бы сигнал, которого там
 *   нет, и именно это версия и отсекает.
 * - **2** — spotty::IInterfacePlugin::liveOptions() и spotty::SettingsField::live: пункты
 *   списка, которые становятся известны только после опроса (узлы на шине CAN). Сломано
 *   и то и другое сразу: новый виртуальный метод сдвигает vtable, новое поле структуры —
 *   раскладку SettingsSchema.
 * - **1** — первый выпуск.
 */
#define SPOTTY_API_VERSION 5

/**
 * \def SPOTTY_INTERFACE_PLUGIN_IID
 * \brief Идентификатор интерфейса для Q_DECLARE_INTERFACE и Q_PLUGIN_METADATA.
 *
 * Завершающая версия («/1.0») участвует в собственной проверке совместимости Qt: если её
 * изменить, старые двоичные файлы плагинов перестанут распознаваться (qobject_cast вернёт
 * nullptr) вместо того, чтобы загрузиться и упасть.
 *
 * \note Это второй, независимый рубеж защиты. #SPOTTY_API_VERSION проверяется нашим кодом
 *       и даёт внятное сообщение; IID проверяется самим Qt ещё до создания объекта.
 */
#define SPOTTY_INTERFACE_PLUGIN_IID "org.spotty.IInterfacePlugin/1.0"
