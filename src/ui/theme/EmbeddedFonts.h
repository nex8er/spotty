/**
 * \file EmbeddedFonts.h
 * \brief Шрифты, встроенные в исполняемый файл.
 */
#pragma once

#include <QString>

namespace spotty {

/**
 * \class EmbeddedFonts
 * \brief Моноширинный шрифт терминала, поставляемый вместе с программой.
 *
 * \par Зачем встраивать
 *
 * Системный моноширинный шрифт у каждой платформы свой: Menlo на macOS, Consolas на
 * Windows, что придётся в Linux. Вывод устройства выглядит по-разному на трёх машинах, а
 * колонка HEX-дампа местами расползается — не все системные «моноширинные» шрифты
 * действительно моноширинны для всего диапазона.
 *
 * FiraCode Nerd Font Mono решает обе задачи сразу: одинаковая картинка всюду и полный
 * набор глифов Nerd Font, которыми прошивки любят рисовать рамки и значки в своём выводе.
 * Без него такой вывод превращается в частокол пустых прямоугольников.
 *
 * \note Лигатуры FiraCode в терминале нежелательны: `!=` склеивается в один знак, и
 *       посчитать столбцы в дампе становится невозможно. Начертание Mono поставляется без
 *       них — поэтому взято именно оно, а не обычное FiraCode.
 */
class EmbeddedFonts
{
public:
    /**
     * \brief Зарегистрировать встроенные шрифты в базе шрифтов Qt.
     *
     * \warning Вызывать после создания QApplication и один раз. Повторный вызов ничего не
     *          делает.
     */
    static void initialize();

    /**
     * \return Семейство встроенного моноширинного шрифта либо пустая строка, если ресурс
     *         не загрузился.
     *
     * Пустая строка — не отказ: вызывающая сторона обязана откатиться на системный
     * моноширинный шрифт. Программа без своего шрифта работает, просто выглядит иначе.
     */
    static QString monospaceFamily();
};

} // namespace spotty
