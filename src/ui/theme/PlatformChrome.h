/**
 * \file PlatformChrome.h
 * \brief Оформление рамки окна средствами операционной системы.
 */
#pragma once

class QWidget;

namespace spotty {

/**
 * \namespace spotty::PlatformChrome
 * \brief То в облике окна, до чего таблица стилей не дотягивается.
 *
 * \par Зачем это нужно
 *
 * Заголовок окна рисует не Qt, а система, и QSS с палитрой на него не влияют. Тёмная тема
 * Spotty со светлым системным заголовком выглядит наполовину чужой — светлая полоса поверх
 * тёмного окна, — и наоборот. Обе системы позволяют это исправить, но только своим вызовом:
 * `DwmSetWindowAttribute` на Windows и `NSWindow.appearance` на macOS.
 *
 * \par Как это вызывается
 *
 * Не из виджетов. spotty::ThemeManager красит окна сам — при смене темы и при показе
 * каждого нового окна верхнего уровня. Диалогу для этого делать ничего не нужно, и
 * забыть об этом при добавлении нового диалога тоже нельзя.
 */
namespace PlatformChrome {

/**
 * \brief Согласовать оформление рамки окна с темой приложения.
 * \param window Окно верхнего уровня; вложенный виджет игнорируется.
 * \param dark Тёмная ли тема сейчас.
 *
 * На системах, где такой возможности нет, не делает ничего — это штатный случай, а не
 * ошибка.
 *
 * \warning Вызывает `QWidget::winId()` и потому создаёт системный дескриптор окна. Вызывать
 *          до показа окна не следует: обращение к дескриптору раньше времени превращает
 *          виджет в «родное» окно и сбрасывает часть уже настроенных его свойств.
 */
void applyWindowAppearance(QWidget *window, bool dark);

} // namespace PlatformChrome

} // namespace spotty
