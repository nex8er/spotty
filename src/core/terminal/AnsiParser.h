/**
 * \file AnsiParser.h
 * \brief Инкрементальный разборщик управляющих последовательностей ANSI.
 */
#pragma once

#include "TextStyle.h"

#include <QByteArray>
#include <QString>
#include <QStringConverter>

namespace spotty {

/**
 * \class AnsiParser
 * \brief Разбирает поток байтов на текст с оформлением и команды управления строкой.
 *
 * \par Что поддерживается
 *
 * - **SGR** (`ESC[…m`) целиком: сброс, жирный, тусклый, курсив, подчёркивание, инверсия,
 *   зачёркивание; цвета 16, 256 (`38;5;n`) и точные (`38;2;r;g;b`).
 * - **Управление строкой**: возврат каретки, забой, табуляция, перевод строки.
 * - **Очистка**: `ESC[K` (в строке) и `ESC[J` (на экране).
 * - Прочие последовательности CSI и OSC распознаются и **отбрасываются**, не попадая в
 *   вывод мусором.
 *
 * Полной эмуляции экрана VT100 нет намеренно: адресация курсора, альтернативный экран и
 * области прокрутки не нужны монитору порта и потребовали бы отдельной модели экрана,
 * несовместимой с журналом, поиском и копированием.
 *
 * \par Инкрементальность
 *
 * Разборщик хранит состояние между вызовами parse(), потому что последовательность легко
 * приходит разорванной: чтение из порта может закончиться ровно между `ESC[` и `31m`.
 * Незавершённый хвост запоминается и достраивается следующей порцией.
 *
 * По той же причине декодирование байтов в текст ведётся через QStringDecoder — он
 * сохраняет состояние и правильно собирает символ UTF-8, разорванный между порциями.
 *
 * \par Использование
 *
 * \code
 * class MySink : public AnsiParser::Sink { ... };
 * MySink sink;
 * AnsiParser parser;
 * parser.parse(chunk, sink);
 * \endcode
 */
class AnsiParser
{
public:
    /**
     * \class Sink
     * \brief Приёмник событий разборщика.
     *
     * Виртуальные вызовы происходят на отрезок текста или управляющий символ, а не на
     * каждый байт, поэтому на пропускную способность не влияют.
     */
    class Sink
    {
    public:
        virtual ~Sink() = default;

        /// \brief Отрезок обычного текста с текущим оформлением.
        virtual void text(QStringView text, const TextStyle &style) = 0;

        /// \brief Перевод строки (0x0A).
        virtual void lineFeed() = 0;

        /**
         * \brief Возврат каретки (0x0D).
         *
         * Курсор переходит в начало текущей строки, не создавая новую. Именно на этом
         * работают индикаторы прогресса, перерисовывающие строку на месте.
         */
        virtual void carriageReturn() = 0;

        /// \brief Забой (0x08): курсор на позицию назад.
        virtual void backspace() = 0;

        /// \brief Табуляция (0x09): курсор до следующей позиции, кратной восьми.
        virtual void tab() = 0;

        /**
         * \brief Очистка в строке (`ESC[K`).
         * \param mode 0 — от курсора до конца, 1 — от начала до курсора, 2 — вся строка.
         */
        virtual void eraseInLine(int mode) = 0;

        /**
         * \brief Очистка экрана (`ESC[J`).
         * \param mode 0 — от курсора вниз, 1 — от начала вверх, 2 и 3 — всё.
         */
        virtual void eraseInDisplay(int mode) = 0;
    };

    AnsiParser();

    /**
     * \brief Задать кодировку принимаемого текста.
     * \param encoding UTF-8 либо Latin-1.
     *
     * Сбрасывает состояние декодера, поэтому вызывать между порциями данных не следует.
     *
     * \note Однобайтовые кодировки вроде CP1251 в Qt 6 доступны только через модуль
     *       Qt5Compat, которого в зависимостях нет. Latin-1 покрывает случай «показать
     *       байты как есть», а для остального остаётся HEX-режим.
     */
    void setEncoding(QStringConverter::Encoding encoding);

    QStringConverter::Encoding encoding() const { return m_encoding; }

    /**
     * \brief Разобрать очередную порцию байтов.
     * \param data Байты как пришли из канала.
     * \param sink Приёмник событий.
     *
     * Незавершённая последовательность и незавершённый символ UTF-8 остаются во
     * внутреннем состоянии до следующего вызова.
     */
    void parse(const QByteArray &data, Sink &sink);

    /**
     * \brief Сбросить состояние: оформление, декодер, незавершённую последовательность.
     *
     * Нужен при открытии канала и при смене направления: оформление, установленное
     * устройством, не должно протекать в отражённый вывод и наоборот.
     */
    void reset();

    /// \brief Текущее накопленное оформление.
    const TextStyle &style() const { return m_style; }

private:
    /// \brief Стадия разбора.
    enum class State {
        Ground,     ///< Обычный текст.
        Escape,     ///< Получен ESC, ждём тип последовательности.
        Csi,        ///< Внутри `ESC[…`, копим параметры.
        Osc,        ///< Внутри `ESC]…`, ждём завершитель.
        OscEscape,  ///< Внутри OSC получен ESC, ждём `\` завершителя ST.
    };

    /// \brief Выдать накопленный текст и очистить накопитель.
    void flushText(Sink &sink);

    /// \brief Обработать завершённую последовательность CSI.
    void handleCsi(QChar finalByte, Sink &sink);

    /// \brief Применить параметры SGR к текущему оформлению.
    void applySgr();

    QStringConverter::Encoding m_encoding = QStringConverter::Utf8;
    QStringDecoder m_decoder;

    State m_state = State::Ground;
    QString m_params;      ///< Накопленные параметры текущей последовательности CSI.
    QString m_pendingText; ///< Текст, ещё не отданный приёмнику.
    TextStyle m_style;
};

} // namespace spotty
