/**
 * \file SettingsMigration.h
 * \brief Перенос настроек, переехавших между версиями.
 */
#pragma once

namespace spotty {

class SettingsStore;

/**
 * \class SettingsMigration
 * \brief Приводит настройки прошлых версий к нынешней раскладке ключей.
 *
 * \par Почему это делает приложение, а не плагины
 *
 * Старые ключи — факт истории программы, и знать о нём каждому плагину незачем. Одно
 * место, которое в следующей версии удаляется целиком.
 *
 * \par Почему это отдельный класс, а не функция в main.cpp
 *
 * Перенос — это код, который выполняется ровно один раз у каждого пользователя и
 * молча решает судьбу его настроек. Ошибка здесь не проявится ни в одном запуске
 * разработчика, зато у всех остальных сотрёт то, что настраивали месяцами. Такому коду
 * нужны тесты, а функция в `main.cpp` недостижима ни для одного набора.
 *
 * \note Все шаги идемпотентны: перенос отрабатывает на каждом запуске, пока его не удалят.
 */
class SettingsMigration
{
public:
    /**
     * \brief Выполнить все переносы и сохранить настройки, если что-то изменилось.
     * \return `true`, если настройки были изменены.
     */
    static bool apply(SettingsStore &store);

private:
    /// \brief Ключи макросов, поиска и журнала — из корня под `plugins/<id>/`.
    static bool movePluginKeys(SettingsStore &store);

    /// \brief Всё, что относилось к `csvchart`, — к `plotter`.
    static bool renameChartToPlotter(SettingsStore &store);
};

} // namespace spotty
