/**
 * \file AppSettings.h
 * \brief Все пользовательские настройки одной структурой.
 */
#pragma once

#include <QHash>
#include <QString>
#include <QStringList>

namespace spotty {

class SettingsStore;

/**
 * \struct AppSettings
 * \brief Полный набор пользовательских настроек с умолчаниями.
 *
 * \par Зачем структура, а не обращения к хранилищу по месту
 *
 * Ключи настроек — это строки, и опечатку в них не поймает ни компилятор, ни проверка
 * типов: настройка просто перестаёт сохраняться. Пока ключи лежали константами в четырёх
 * разных файлах, они уже начали расходиться, а диалог настроек стал бы пятым местом,
 * знающим те же строки.
 *
 * Здесь ключ и умолчание объявлены ровно один раз. Диалог правит копию структуры,
 * владелец записывает её обратно и раздаёт значения потребителям — за один проход, без
 * поиска «кто ещё читает этот ключ».
 *
 * \note Геометрия окна, положение разделителя и выбранный интерфейс сюда не входят: это
 *       состояние окна, а не то, что человек настраивает осознанно.
 */
struct AppSettings
{
    // --- Общие -----------------------------------------------------------------------

    /// \brief Язык интерфейса: `"system"`, `"en"` или `"ru"`.
    QString language = QStringLiteral("system");

    /// \brief Тема оформления: `"dark"` или `"light"`.
    QString theme = QStringLiteral("dark");

    /**
     * \brief Открывать запомненный интерфейс при запуске.
     *
     * По умолчанию выключено: открытие порта дёргает DTR, а у многих плат это сброс, и
     * оно же перехватывает порт у другой программы.
     */
    bool autoOpenLastInterface = false;

    /// \brief Не запускать второй экземпляр, а показать окно уже запущенного.
    bool singleInstance = true;

    // --- Терминал --------------------------------------------------------------------

    /// \brief Семейство шрифта вывода. Пустая строка — системный моноширинный.
    QString fontFamily;

    /// \brief Размер шрифта в пунктах. Ноль — размер системного моноширинного.
    int fontSize = 0;

    /// \brief Предел числа строк в буфере.
    int maxLines = 20000;

    bool showTimestamps = false;

    /// \brief Показывать разницу с предыдущей строкой вместо абсолютного времени.
    bool relativeTimestamps = false;

    /// \brief Формат абсолютной метки в записи QDateTime::toString().
    QString timestampFormat = QStringLiteral("HH:mm:ss.zzz");

    bool showDirection = true;

    /// \brief Показывать номера строк в колонке слева.
    bool showLineNumbers = false;

    /// \brief Скрывать из вывода строки телеметрии, состоящие из чисел через разделитель.
    bool csvFilter = false;

    /// \brief Разделитель полей для распознавания телеметрии.
    QString csvSeparator = QStringLiteral(",");

    /// \brief Отражать отправленное в терминал.
    bool localEcho = true;

    int hexBytesPerRow = 16;

    /// \brief Режим показа: `"text"` или `"hex"`.
    QString viewMode = QStringLiteral("text");

    /// \brief Кодировка принимаемого текста: `"utf-8"` или `"latin1"`.
    QString encoding = QStringLiteral("utf-8");

    /**
     * \brief Шестнадцать базовых цветов ANSI в записи `"#rrggbb"`.
     *
     * Пустой список означает «взять из темы». Так смена темы продолжает менять цвета до
     * тех пор, пока пользователь не задал свои: сохранять палитру темы в настройки при
     * первом запуске значило бы намертво привязать вывод к теме, выбранной случайно.
     */
    QStringList ansiPalette;

    // --- Отправка --------------------------------------------------------------------

    /// \brief Формат по умолчанию, значение spotty::DataCodec::Format.
    int sendFormat = 0;

    /// \brief Терминация по умолчанию, значение spotty::DataCodec::Termination (CR+LF).
    int sendTermination = 3;

    /// \brief Сколько записей хранить в истории отправки.
    int historySize = 500;

    // Настройки журналирования переехали к плагину `logging`: они принадлежат ему, а не
    // программе, и живут в `plugins/logging/*`. Держать их здесь после этого значило бы
    // иметь два места для одного факта — ровно то, из-за чего ключи настроек когда-то и
    // свели в этот класс.

    // --- Данные ----------------------------------------------------------------------

    /// \brief Правило разбиения потока, значение spotty::Packetizer::Mode.
    int packetizerMode = 0;

    /// \brief Межбайтовая пауза, мс.
    int packetizerTimeoutMs = 20;

    /// \brief Разделитель для режима делимитера, в шестнадцатеричной записи.
    QString packetizerDelimiterHex = QStringLiteral("0A");

    int packetizerFixedLength = 16;

    // --- Горячие клавиши -------------------------------------------------------------

    /**
     * \brief Сочетания клавиш действий приложения по их идентификаторам.
     *
     * Отсутствующий идентификатор означает сочетание по умолчанию, заданное в коде
     * действия. Хранится только то, что пользователь изменил.
     */
    QHash<QString, QString> shortcuts;

    /// \brief Прочитать настройки из хранилища, подставив умолчания.
    static AppSettings load(const SettingsStore &store);

    /// \brief Записать настройки в хранилище.
    void save(SettingsStore &store) const;

    /// \brief Каталог логов с учётом умолчания.
};

} // namespace spotty
